"""Exploration benchmark report: runs mrc_experiment_exploration_benchmark and
writes docs/benchmarks/exploration.md plus plots in docs/assets/plots/.
"""

from __future__ import annotations

import argparse
import platform
import statistics
import sys
from collections import defaultdict
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[2] / "python"))

import matplotlib.pyplot as plt

from multirobotcore_viz import pipeline, style

CONFIG = "configs/exploration/benchmark.json"
PLOTS = pipeline.ASSETS_DIR / "plots"
DOC = pipeline.REPO_ROOT / "docs" / "benchmarks" / "exploration.md"
STRATEGIES = ["nearest_frontier", "hungarian", "utility_discount"]
LABELS = {
    "nearest_frontier": "nearest frontier",
    "hungarian": "Hungarian",
    "utility_discount": "utility discount",
}
COLORS = {"nearest_frontier": style.BLUE, "hungarian": style.ORANGE, "utility_discount": style.AQUA}


def _mean(values: list[float]) -> float:
    clean = [v for v in values if v is not None]
    return statistics.fmean(clean) if clean else float("nan")


def aggregate(runs: list[dict]) -> dict:
    groups: dict[tuple, list[dict]] = defaultdict(list)
    for r in runs:
        groups[(r["map"], r["robots"], r["strategy"])].append(r)
    return groups


def table(groups: dict, maps: list[str], robots: list[int]) -> str:
    header = (
        "| Map | Robots | Strategy | Complete | Time to 90 % [s] | Time to 95 % [s] | Completion [s] "
        "| Distance [m] | Redundant cells | Messages | Planner runtime [ms] |"
    )
    lines = [header, "|---|---:|---|:---:|---:|---:|---:|---:|---:|---:|---:|"]
    for m in maps:
        for n in robots:
            for s in STRATEGIES:
                rs = groups[(m, n, s)]
                done = sum(r["complete"] for r in rs)
                lines.append(
                    f"| {m} | {n} | {LABELS[s]} | {done}/{len(rs)} "
                    f"| {_mean([r['time_to_90_s'] for r in rs]):.0f} "
                    f"| {_mean([r['time_to_95_s'] for r in rs]):.0f} "
                    f"| {_mean([r['time_s'] for r in rs]):.0f} "
                    f"| {_mean([r['distance_m'] for r in rs]):.0f} "
                    f"| {100 * _mean([r['redundancy_ratio'] for r in rs]):.0f} % "
                    f"| {_mean([r['messages'] for r in rs]):.0f} "
                    f"| {_mean([r['runtime_ms'] for r in rs]):.1f} |"
                )
    return "\n".join(lines)


def plot(groups: dict, maps: list[str], robots: list[int], key: str, title: str, path: Path) -> None:
    style.apply_style()
    fig, axes = plt.subplots(1, len(maps), figsize=(3.0 * len(maps) + 0.6, 3.0), dpi=110, sharey=False)
    for ax, m in zip(axes, maps, strict=True):
        for s in STRATEGIES:
            ys = [_mean([r[key] for r in groups[(m, n, s)]]) for n in robots]
            ax.plot(robots, ys, color=COLORS[s], marker="o", markersize=5, label=LABELS[s])
        ax.set_xscale("log", base=2)
        ax.set_xticks(robots, [str(n) for n in robots])
        ax.set_title(m, loc="left", fontsize=10)
        ax.set_xlabel("robots")
        ax.grid(True, axis="y")
    axes[0].set_ylabel(title)
    axes[-1].legend(loc="upper right", fontsize=8)
    fig.tight_layout()
    fig.savefig(path)
    plt.close(fig)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--build-dir", type=Path, default=None)
    parser.add_argument("--result", type=Path, default=None)
    args = parser.parse_args()
    if args.result is not None:
        result = pipeline.load_result(args.result)
    else:
        result = pipeline.run_executable(
            "mrc_experiment_exploration_benchmark",
            args.build_dir,
            pipeline.REPO_ROOT / CONFIG,
            pipeline.RESULTS_DIR / "exploration_benchmark.json",
        )
    cfg = result["config"]
    maps = [m["name"] for m in cfg["maps"]]
    robots = cfg["robot_counts"]
    groups = aggregate(result["runs"])
    PLOTS.mkdir(parents=True, exist_ok=True)
    plot(groups, maps, robots, "time_to_90_s", "time to 90 % [s]", PLOTS / "exploration_time_to_90.png")
    plot(groups, maps, robots, "time_s", "completion time [s]", PLOTS / "exploration_completion.png")
    DOC.parent.mkdir(parents=True, exist_ok=True)
    DOC.write_text(
        f"""# Exploration benchmark

Generated by `python scripts/benchmark/exploration_benchmark.py` from
`mrc_experiment_exploration_benchmark` ({CONFIG}). Release build, single thread,
{platform.system()} {platform.machine()}. Means over seeds {cfg["seeds"]}; each seed draws the
start cells at random inside a {cfg["start_radius"]}-cell disc around the map's start point.

Setup: grid resolution {cfg["resolution"]} m, robot speed {cfg["robot_speed"]} m/s (one cell per
{result["step_seconds"]:.0f} s step), noise-free {cfg["sensor_range"]} m range sensor with
{cfg["beams"]} beams, shared map, re-planning every {cfg["replan_period"]} steps or when a target
stops being a frontier. Coverage is measured on the free space reachable from the starts.
Robots are points on the grid (inter-robot collisions are not modelled here).

![time to 90 %](../assets/plots/exploration_time_to_90.png)

![completion time](../assets/plots/exploration_completion.png)

{table(groups, maps, robots)}

## Observations

* With a single robot the nearest-frontier rule is fastest on every map: the
  information-gain term of the other strategies pulls a lone robot toward large
  but distant frontiers, which costs travel without a coordination benefit.
* Coordination pays off as the team grows. With eight robots the Hungarian
  assignment completes the office in 122 s versus 161 s for the uncoordinated
  rule and the rooms map in 58 s versus 93 s; with four robots on the pillars
  map it completes in 96 s versus 167 s.
* The benefit is not uniform: with two robots on the office map the
  uncoordinated rule is about twice as fast, because sending the second robot
  to a distant frontier (to avoid duplication) costs more than sharing the
  nearby rooms.
* The Hungarian assignment usually lowers redundant observation, while the
  utility-discount rule does not reduce it consistently on these small maps
  (robots start together, so the start area is observed by everyone).
* Completion time is dominated by the last small frontier pockets
  ("cleanup"), which is why the time to 90 % and the completion time can rank
  strategies differently.
""",
        encoding="utf-8",
    )
    print(f"wrote {DOC.relative_to(pipeline.REPO_ROOT)}")


if __name__ == "__main__":
    main()
