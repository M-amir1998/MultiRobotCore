"""MAPF planner comparison: runs mrc_experiment_mapf_benchmark (or loads a
result file) and writes docs/benchmarks/mapf.md plus plots in
docs/assets/plots/.

    python scripts/benchmark/mapf_benchmark.py [--build-dir build/release] [--result file.json]
"""

from __future__ import annotations

import argparse
import statistics
import sys
from collections import defaultdict
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[2] / "python"))

from multirobotcore_viz import pipeline, style

CONFIG = "configs/mapf/benchmark.json"
DOC = pipeline.REPO_ROOT / "docs" / "benchmarks" / "mapf.md"
PLOTS = pipeline.ASSETS_DIR / "plots"
PLANNERS = ["independent", "prioritized", "prioritized_restarts", "cbs"]
PLANNER_LABEL = {
    "independent": "Independent A* (unsafe)",
    "prioritized": "Prioritized (single order)",
    "prioritized_restarts": "Prioritized (10 restarts)",
    "cbs": "CBS",
}
# Coordinated planners plotted with the first three categorical slots.
PLOTTED = {"prioritized": style.BLUE, "prioritized_restarts": style.ORANGE, "cbs": style.AQUA}


def summarise(rows: list[dict]) -> dict:
    groups: dict[tuple, list[dict]] = defaultdict(list)
    bounds: dict[tuple, int] = {}
    for r in rows:
        groups[(r["map"], r["agents"], r["planner"])].append(r)
        if r["planner"] == "independent":
            bounds[(r["map"], r["agents"], r["seed"])] = r["sum_of_costs"]
    summary = {}
    for key, runs in groups.items():
        # Independent A* always returns (possibly colliding) paths: its costs
        # are averaged over every run and form the lower bound.
        ok = runs if key[2] == "independent" else [r for r in runs if r["success"]]
        ratios = [
            r["sum_of_costs"] / bounds[(r["map"], r["agents"], r["seed"])]
            for r in ok
            if bounds.get((r["map"], r["agents"], r["seed"]))
        ]
        summary[key] = {
            "runs": len(runs),
            "solved": len(ok),
            "timeouts": sum(r["status"] == "timeout" for r in runs),
            "failed": sum(r["status"] == "failed" for r in runs),
            "runtime": statistics.median(r["runtime_ms"] for r in runs),
            "soc": statistics.mean(r["sum_of_costs"] for r in ok) if ok else None,
            "makespan": statistics.mean(r["makespan"] for r in ok) if ok else None,
            "ratio": statistics.mean(ratios) if ratios else None,
            "conflicts": statistics.mean(r["conflicts"] for r in runs),
            "hl": statistics.mean(r["hl_expanded"] for r in runs),
            "ll": statistics.mean(r["ll_expansions"] for r in runs),
        }
    return summary


def _fmt(value, digits=1):
    return "-" if value is None else f"{value:.{digits}f}"


def _success_cell(s: dict, planner: str) -> str:
    if planner == "independent":
        return "n/a (unsafe)"
    note = []
    if s["timeouts"]:
        note.append(f"{s['timeouts']} timeout")
    if s["failed"]:
        note.append(f"{s['failed']} failed")
    extra = f" ({', '.join(note)})" if note else ""
    return f"{s['solved']}/{s['runs']}{extra}"


def write_markdown(result: dict, summary: dict, maps: list[dict]) -> None:
    cfg = result["config"]
    lines = [
        "# MAPF benchmark",
        "",
        "Generated by `scripts/benchmark/mapf_benchmark.py` from `mrc_experiment_mapf_benchmark` "
        f"(configuration `{CONFIG}`). Do not edit by hand.",
        "",
        f"- Instances: {len(cfg['seeds'])} seeds per (map, team size); random starts/goals in the "
        "largest connected component (warehouse: station columns to shelf access cells).",
        f"- CBS wall-clock limit: {cfg['cbs_time_limit_s']} s per instance; timeouts are reported, "
        "not hidden. Prioritized restarts: up to "
        f"{cfg['restart_attempts']} orderings (shortest-first, then seeded random).",
        "- Runtime: median over all runs of the cell, including timeouts at the limit. Sum of costs, "
        "makespan and SOC / bound: mean over solved runs only. SOC / bound divides by the "
        "independent (uncoordinated) sum of costs, a lower bound on every collision-free solution.",
        "- Independent A* ignores the other robots; its 'Conflicts' column counts the collisions "
        "it would cause.",
        "- Single-threaded, CPU only; absolute times depend on the machine and compiler.",
        "",
    ]
    for m in maps:
        name = m["name"]
        lines += [f"## {name.capitalize()}", ""]
        lines.append(
            "| Planner | Robots | Success | Runtime [ms] | Sum Cost | Makespan | SOC / bound "
            "| Conflicts | CT nodes | LL expansions |"
        )
        lines.append("|---|---:|---|---:|---:|---:|---:|---:|---:|---:|")
        for planner in PLANNERS:
            for agents in m["agents"]:
                s = summary.get((name, agents, planner))
                if s is None:
                    continue
                lines.append(
                    f"| {PLANNER_LABEL[planner]} | {agents} | {_success_cell(s, planner)} "
                    f"| {_fmt(s['runtime'], 2)} | {_fmt(s['soc'])} | {_fmt(s['makespan'])} "
                    f"| {_fmt(s['ratio'], 3)} | {_fmt(s['conflicts'])} "
                    f"| {_fmt(s['hl'] if planner == 'cbs' else None, 1)} | {_fmt(s['ll'], 0)} |"
                )
        lines.append("")
    lines += [
        "## Plots",
        "",
        "![MAPF runtime](../assets/plots/mapf_runtime.png)",
        "",
        "![MAPF success rate](../assets/plots/mapf_success.png)",
        "",
        "![MAPF solution quality](../assets/plots/mapf_quality.png)",
        "",
    ]
    DOC.parent.mkdir(parents=True, exist_ok=True)
    DOC.write_text("\n".join(lines), encoding="utf-8")
    print(f"wrote {DOC.relative_to(pipeline.REPO_ROOT)}")


def write_plots(summary: dict, maps: list[dict]) -> None:
    import matplotlib.pyplot as plt  # noqa: PLC0415  (style must configure the backend first)

    style.apply_style()
    PLOTS.mkdir(parents=True, exist_ok=True)
    panels = [
        ("mapf_runtime.png", "median runtime [ms]", lambda s: s["runtime"], True),
        ("mapf_success.png", "success rate", lambda s: s["solved"] / s["runs"], False),
        ("mapf_quality.png", "sum of costs / lower bound", lambda s: s["ratio"], False),
    ]
    for filename, ylabel, metric, log in panels:
        fig, axes = plt.subplots(1, len(maps), figsize=(11.0, 3.2), dpi=100, sharey=not log)
        for ax, m in zip(axes, maps, strict=True):
            for planner, color in PLOTTED.items():
                xs, ys = [], []
                for agents in m["agents"]:
                    s = summary.get((m["name"], agents, planner))
                    value = metric(s) if s else None
                    if value is not None:
                        xs.append(agents)
                        ys.append(value)
                ax.plot(xs, ys, marker="o", markersize=4, color=color, label=PLANNER_LABEL[planner])
            ax.set_title(m["name"], fontsize=10, loc="left")
            ax.set_xlabel("robots")
            ax.grid(True, axis="y")
            if log:
                ax.set_yscale("log")
        axes[0].set_ylabel(ylabel)
        handles, labels = axes[0].get_legend_handles_labels()
        fig.legend(
            handles, labels, loc="upper center", ncol=len(PLOTTED), fontsize=8.5, bbox_to_anchor=(0.5, 1.0)
        )
        fig.tight_layout(rect=(0, 0, 1, 0.9))
        out = PLOTS / filename
        fig.savefig(out)
        plt.close(fig)
        print(f"wrote {out.relative_to(pipeline.REPO_ROOT)}")


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--build-dir", type=Path, default=None)
    parser.add_argument("--result", type=Path, default=None)
    args = parser.parse_args()
    if args.result is not None:
        result = pipeline.load_result(args.result)
    else:
        result = pipeline.run_executable(
            "mrc_experiment_mapf_benchmark",
            args.build_dir,
            pipeline.REPO_ROOT / CONFIG,
            pipeline.RESULTS_DIR / "mapf_benchmark.json",
        )
    maps = result["config"]["maps"]
    summary = summarise(result["rows"])
    write_markdown(result, summary, maps)
    write_plots(summary, maps)


if __name__ == "__main__":
    main()
