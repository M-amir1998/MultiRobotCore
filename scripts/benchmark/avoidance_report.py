"""Runs the collision-avoidance experiment and writes the benchmark report.

Outputs:
  docs/benchmarks/avoidance.md                generated tables
  docs/assets/plots/avoidance_makespan.png    time to complete vs. robot count
  docs/assets/plots/avoidance_contacts.png    robot-robot contact events vs. robot count
  docs/assets/plots/avoidance_compute.png     computation time per control step
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

import matplotlib.pyplot as plt

sys.path.insert(0, str(Path(__file__).resolve().parents[2] / "python"))

from multirobotcore_viz import pipeline, style

CONFIG = "configs/avoidance/benchmark.json"
SCENARIOS = {
    "circle_swap": "Circle swap",
    "random_crossing": "Random crossing",
    "doorway": "Doorway (one way)",
}
METHODS = {
    "orca": ("ORCA", style.BLUE),
    "rvo": ("RVO (sampled)", style.ORANGE),
    "vo": ("VO (sampled)", style.AQUA),
}
PLOTS = pipeline.ASSETS_DIR / "plots"
REPORT = pipeline.REPO_ROOT / "docs" / "benchmarks" / "avoidance.md"


def series(records: list[dict], scenario: str, method: str, key: str) -> tuple[list[int], list[float]]:
    rows = sorted(
        (r for r in records if r["scenario"] == scenario and r["method"] == method), key=lambda r: r["robots"]
    )
    return [r["robots"] for r in rows], [r["metrics"][key] for r in rows]


def plot(records: list[dict], key: str, ylabel: str, title: str, path: Path, log: bool = False) -> None:
    style.apply_style()
    fig, axes = plt.subplots(1, 3, figsize=(10.5, 3.3), dpi=100, sharey=log)
    for ax, (scenario, label) in zip(axes, SCENARIOS.items(), strict=True):
        top = 0.0
        for method, (name, color) in METHODS.items():
            x, y = series(records, scenario, method, key)
            if not x:
                continue
            top = max(top, *y)
            ax.plot(x, y, color=color, marker="o", markersize=5, label=name)
        if not log:
            ax.set_ylim(0.0, max(1.0, 1.12 * top))
        ax.set_title(label, loc="left", fontsize=10.5)
        ax.set_xlabel("robots")
        ax.set_xscale("log")
        ax.set_xticks([5, 10, 20, 50, 100], labels=["5", "10", "20", "50", "100"])
        ax.minorticks_off()
        if log:
            ax.set_yscale("log")
        ax.grid(True, axis="y")
    axes[0].set_ylabel(ylabel)
    axes[-1].legend(loc="upper left", fontsize=8.5)
    fig.suptitle(title, x=0.01, ha="left", fontsize=12, weight="bold")
    fig.tight_layout()
    path.parent.mkdir(parents=True, exist_ok=True)
    fig.savefig(path)
    plt.close(fig)


def fmt(value, digits: int = 2) -> str:
    if value is None:
        return "-"
    if isinstance(value, bool):
        return "yes" if value else "no"
    if isinstance(value, float):
        return f"{value:.{digits}f}"
    return str(value)


def table(records: list[dict], scenario: str) -> list[str]:
    lines = [
        "| Method | Robots | Success | Reached | Contacts (robot / obstacle) | Min clearance [m] | "
        "Makespan [s] | Mean time to goal [s] | Path efficiency | Velocity deviation [m/s] | Stall | "
        "Compute [ms/step] |",
        "|---|---:|:---:|---:|---:|---:|---:|---:|---:|---:|:---:|---:|",
    ]
    rows = sorted(
        (r for r in records if r["scenario"] == scenario),
        key=lambda r: (r["robots"], list(METHODS).index(r["method"])),
    )
    for r in rows:
        m = r["metrics"]
        lines.append(
            f"| {METHODS[r['method']][0]} | {r['robots']} | {fmt(m['success'])} | "
            f"{m['reached']}/{r['robots']} | "
            f"{m['robot_collisions']} / {m['obstacle_collisions']} | {fmt(m['min_pair_clearance'], 3)} | "
            f"{fmt(m['makespan'], 1)} | {fmt(m['mean_time_to_goal'], 1)} | {fmt(m['path_efficiency'], 3)} | "
            f"{fmt(m['mean_velocity_deviation'], 3)} | {fmt(m['stalled'])} | {fmt(m['ms_per_step'], 3)} |"
        )
    return lines


def write_report(result: dict) -> None:
    records = result["records"]
    cfg = result["config"]
    av = cfg["avoidance"]
    lines = [
        "# Collision-avoidance benchmark",
        "",
        "<!-- Generated by scripts/benchmark/avoidance_report.py; do not edit by hand. -->",
        "",
        "Deterministic simulator runs (`apps/benchmarks/avoidance_benchmark.cpp`, configuration "
        f"`{CONFIG}`, seed {cfg['seed']}). Disc robots of radius {cfg['robot_radius']} m, "
        f"maximum speed {cfg['max_speed']} m/s, control period {cfg['dt']} s, single-integrator "
        "dynamics. Preferred velocities point at the goal (via door waypoints in the doorway "
        f"scenario) and carry {cfg['preference_perturbation']} m/s of seeded noise to break exact "
        "symmetries. Avoidance parameters: tau = "
        f"{av['time_horizon']} s (obstacles {av['obstacle_time_horizon']} s), sensing radius "
        f"{av['neighbor_distance']} m, at most {av['max_neighbors']} neighbours, safety margin "
        f"{av['safety_margin']} m; sampled methods use {av['speed_rings']} x {av['angle_samples']} "
        "candidate velocities.",
        "",
        "Metric definitions: *success* = every robot reached its goal with zero contact events; "
        "*contacts* are simulator contact events (a pair entering overlap, or a robot touching an "
        "obstacle/boundary); *min clearance* is the smallest surface-to-surface distance between "
        "robots; *path efficiency* is straight-line distance divided by travelled distance; "
        "*velocity deviation* is the mean of ||v - v_pref||; *stall* is the simulator heuristic "
        "(all active robots moved less than 5 cm in 4 s), which ends the run. Compute time is the "
        "wall-clock time of the whole control loop per step on the benchmark machine, single "
        "threaded; neighbour search is brute force O(N^2).",
        "",
        "![makespan](../assets/plots/avoidance_makespan.png)",
        "",
        "![contacts](../assets/plots/avoidance_contacts.png)",
        "",
        "![compute](../assets/plots/avoidance_compute.png)",
        "",
    ]
    for scenario, label in SCENARIOS.items():
        lines += [f"## {label}", "", *table(records, scenario), ""]
    lines += [
        "## Reading the results",
        "",
        "- Velocity obstacles assume the other robot keeps its velocity. Two robots that both "
        "avoid therefore over-react and oscillate, and in crowded scenes VO produces contact "
        "events. RVO and ORCA share the avoidance effort and avoid these artefacts.",
        "- ORCA's guarantee (no collision within tau) holds when every robot's linear program is "
        "feasible and neighbourhoods are mutual. In dense crowds the program becomes infeasible and "
        "the fallback minimises the largest constraint violation, so small overlaps become possible; "
        "the safety margin absorbs most of them.",
        "- Local methods have no global awareness. One-way flow through a door works with a waypoint "
        "route, but counterflow through the same door or a single-file corridor swap congests or "
        "deadlocks (see `docs/assets/avoidance_bottleneck.gif`). These cases require coordination at "
        "the planning level (e.g. multi-agent path finding) rather than better local avoidance.",
        "- A stall flags the heuristic condition described above; it is not a formal deadlock proof.",
        "",
    ]
    REPORT.parent.mkdir(parents=True, exist_ok=True)
    REPORT.write_text("\n".join(lines), encoding="utf-8", newline="\n")
    print(f"wrote {REPORT.relative_to(pipeline.REPO_ROOT)}")


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--build-dir", type=Path, default=None)
    parser.add_argument("--result", type=Path, default=None, help="reuse an existing result JSON")
    args = parser.parse_args()
    if args.result is not None:
        result = pipeline.load_result(args.result)
    else:
        result = pipeline.run_executable(
            "mrc_experiment_avoidance_benchmark",
            args.build_dir,
            pipeline.REPO_ROOT / CONFIG,
            pipeline.RESULTS_DIR / "avoidance_benchmark.json",
        )
    records = result["records"]
    plot(
        records,
        "makespan",
        "makespan [s]",
        "Time until the last robot arrives",
        PLOTS / "avoidance_makespan.png",
    )
    plot(
        records,
        "robot_collisions",
        "contact events",
        "Robot-robot contact events",
        PLOTS / "avoidance_contacts.png",
    )
    plot(
        records,
        "ms_per_step",
        "ms per control step",
        "Computation time per control step (all robots)",
        PLOTS / "avoidance_compute.png",
        log=True,
    )
    write_report(result)


if __name__ == "__main__":
    main()
