"""Builds benchmark pages and plots for consensus, formation and allocation.

Reads results/experiments/{consensus,formation,allocation}_benchmark.json
(written by the mrc_experiment_* executables; pass --run to execute them)
and writes docs/benchmarks/*.md and docs/assets/plots/*.png.
"""

from __future__ import annotations

import argparse
import platform
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[2] / "python"))

from multirobotcore_viz import pipeline
from multirobotcore_viz.plots import fmt, line_chart, markdown_table

ROOT = pipeline.REPO_ROOT
RESULTS = ROOT / "results" / "experiments"
DOCS = ROOT / "docs" / "benchmarks"
PLOTS = ROOT / "docs" / "assets" / "plots"
EXPERIMENTS = {
    "consensus": "configs/consensus/benchmark.json",
    "formation": "configs/formation/benchmark.json",
    "allocation": "configs/allocation/benchmark.json",
    "optimization": "configs/optimization/distributed_optimization.json",
}


def header(title: str, command: str, config: str) -> str:
    return (
        f"# {title}\n\n"
        f"Generated by `scripts/benchmark/coordination_report.py` from the `{command}` experiment "
        f"(configuration `{config}`; seeds and parameters are also recorded in the result file). "
        f"Machine: {platform.system()} {platform.machine()}, CPU only, Release build. Runtimes are "
        "wall-clock and indicative only.\n\n"
    )


def consensus_page(result: dict) -> None:
    rows = []
    iterations: dict[str, tuple[list, list]] = {}
    for r in result["scaling"]:
        rows.append(
            [
                r["topology"],
                r["robots"],
                fmt(r["lambda2"]["mean"], 3),
                fmt(r["iterations"]["mean"]),
                fmt(r["messages"]["mean"]),
                fmt(r["runtime_ms"]["mean"], 3),
            ]
        )
        xs, ys = iterations.setdefault(r["topology"], ([], []))
        xs.append(r["robots"])
        ys.append(r["iterations"]["mean"])
    robust_rows = []
    robust_series: dict[str, tuple[list, list]] = {}
    for r in result["robustness"]:
        robust_rows.append(
            [
                r["topology"],
                r["policy"],
                f"{100 * r['drop_rate']:.0f}%",
                fmt(r["rounds_to_agreement"]["mean"]),
                f"{100 * r['relative_bias']['mean']:.2f}%",
                f"{100 * r['delivery_ratio']['mean']:.1f}%",
                r["failures"],
            ]
        )
        key = f"{r['topology']} / {r['policy']}"
        xs, ys = robust_series.setdefault(key, ([], []))
        xs.append(100 * r["drop_rate"])
        ys.append(r["rounds_to_agreement"]["mean"])
    line_chart(
        iterations,
        "robots",
        "iterations to 1e-4 relative disagreement",
        "Consensus: iterations vs. team size",
        PLOTS / "consensus_iterations.png",
        logx=True,
        logy=True,
    )
    line_chart(
        robust_series,
        "message drop rate [%]",
        "rounds to agreement (1e-3)",
        "Consensus under message loss (20 robots)",
        PLOTS / "consensus_robustness.png",
    )
    text = header("Consensus benchmarks", "mrc_experiment_consensus_benchmark", EXPERIMENTS["consensus"])
    text += (
        "Synchronous discrete consensus `x(k+1) = (I - eps L) x(k)` with `eps = 0.9 / d_max`, initial "
        "values uniform in [0, 10], stopping at a disagreement of 1e-4 of the initial range. Messages "
        "count one value per directed edge per round. Mean over seeds.\n\n"
    )
    text += markdown_table(["Topology", "Robots", "lambda_2", "Iterations", "Messages", "Runtime [ms]"], rows)
    text += "\n\n![iterations](../assets/plots/consensus_iterations.png)\n\n"
    text += (
        "Iterations scale with `1 / (eps * lambda_2)`: complete graphs agree in a handful of rounds while "
        "paths and rings slow down quadratically with team size, exactly as the spectral bound predicts.\n\n"
        "## Robustness to message loss\n\n"
        "Message-passing consensus through the network simulator with independent random loss. *skip* "
        "omits a neighbour whose message was lost; *last_received* reuses its most recent value. Bias is "
        "the distance between the agreement value and the initial average, relative to the initial range: "
        "lossy exchanges are not symmetric, so the average is no longer preserved exactly.\n\n"
    )
    text += markdown_table(
        ["Topology", "Policy", "Drop rate", "Rounds", "Bias", "Delivered", "Failures"], robust_rows
    )
    text += "\n\n![robustness](../assets/plots/consensus_robustness.png)\n\n"
    text += (
        "Agreement is still reached under 20% loss (the union of effective graphs stays connected), at "
        "the cost of more rounds and a small bias. These results do not imply guarantees beyond the "
        "assumptions of the joint-connectivity results cited in the consensus documentation.\n"
    )
    (DOCS / "consensus.md").write_text(text, encoding="utf-8")


def formation_page(result: dict) -> None:
    rows = []
    for r in result["controllers"]:
        m = r["metrics"]
        conv = (
            f"{m['convergence_time']['mean']:.1f} s ({m['converged_runs']}/{m['runs']})"
            if m["converged_runs"]
            else f"not converged (0/{m['runs']})"
        )
        rows.append(
            [
                r["controller"].replace("_", "-"),
                r["formation"],
                fmt(m["rmse"]["mean"], 3),
                conv,
                fmt(m["min_distance"]["min"], 3),
            ]
        )
    moving = [
        [
            ("with" if r["feedforward"] else "without") + " feedforward",
            r["leader_speed"],
            fmt(r["steady_state_rmse"], 3),
        ]
        for r in result["moving_leader"]
    ]
    topo = [
        [
            f"{100 * r['edge_dropout']:.0f}%",
            fmt(r["metrics"]["rmse"]["mean"], 3),
            f"{r['metrics']['converged_runs']}/{r['metrics']['runs']}",
        ]
        for r in result["topology_changes"]
    ]
    robust = []
    series: dict[str, tuple[list, list]] = {}
    for r in result["robustness"]:
        robust.append(
            [
                f"{100 * r['drop_rate']:.0f}%",
                r["noise"],
                fmt(r["mean_rmse"]["mean"], 3),
                f"{100 * r['path_progress']['mean']:.1f}%",
                fmt(r["contacts"]["mean"], 2),
                fmt(r["messages_sent"]["mean"]),
            ]
        )
        xs, ys = series.setdefault(f"noise {r['noise']} m", ([], []))
        xs.append(100 * r["drop_rate"])
        ys.append(r["mean_rmse"]["mean"])
    line_chart(
        series,
        "message drop rate [%]",
        "mean slot RMSE [m]",
        "Formation mission under message loss and noise",
        PLOTS / "formation_robustness.png",
    )
    text = header("Formation benchmarks", "mrc_experiment_formation_benchmark", EXPERIMENTS["formation"])
    text += (
        "Seven single-integrator robots start from random perturbations (+-1.5 m) of the desired shape and "
        "run for 40 s with a 1 m/s speed limit. Leader-follower and consensus (pinned at robot 0, ring "
        "graph) are measured against the absolute slots; the distance-based law (Henneberg graph) only "
        "controls inter-robot distances and is measured after the best rigid alignment. Convergence means "
        "RMSE < 5 cm until the end of the run.\n\n"
    )
    text += markdown_table(
        ["Controller", "Formation", "Formation RMSE [m]", "Convergence", "Min Distance [m]"], rows
    )
    text += (
        "\n\nThe distance-based law cannot stabilise collinear formations (line): the framework is not "
        "infinitesimally rigid, so distances alone do not determine the shape. Pure formation laws do not "
        "model robot size; minimum distances below 2 r indicate where a safety layer (separation barrier, "
        "velocity obstacles) is required.\n\n## Moving leader\n\n"
    )
    text += markdown_table(["Leader-follower", "Leader speed [m/s]", "Steady-state RMSE [m]"], moving)
    text += "\n\nWithout velocity feedforward the steady-state lag equals `v / k` (0.5 m/s, k = 1).\n\n"
    text += "## Topology changes\n\nConsensus formation where every edge of the complete graph drops out "
    text += "independently at every control step.\n\n"
    text += markdown_table(["Edge dropout", "Final RMSE [m]", "Converged runs"], topo)
    text += "\n\n## Integrated mission robustness\n\nThe passage mission (gather, V, column, V) with lossy "
    text += "leader-state relay and Gaussian noise on position estimates.\n\n"
    text += markdown_table(
        ["Drop rate", "Noise [m]", "Mean RMSE [m]", "Path progress", "Contacts", "Messages"], robust
    )
    text += "\n\n![robustness](../assets/plots/formation_robustness.png)\n"
    (DOCS / "formation.md").write_text(text, encoding="utf-8")


def allocation_page(result: dict) -> None:
    rows = []
    runtime: dict[str, tuple[list, list]] = {
        "Hungarian": ([], []),
        "Auction (Gauss-Seidel)": ([], []),
        "Auction (Jacobi)": ([], []),
    }
    messages: dict[str, tuple[list, list]] = {}
    for r in result["static"]:
        n, m = r["robots"], r["tasks"]
        h = r["hungarian"]
        gs = r["auction_gauss_seidel"]
        ja = r["auction_jacobi"]
        cost = h["cost"]["mean"]
        rows.append([f"Hungarian ({r['case']})", n, m, fmt(cost, 4), fmt(h["runtime_ms"]["mean"], 3), "-"])
        rows.append(
            [
                f"Auction GS ({r['case']})",
                n,
                m,
                fmt(cost * (1 + gs["gap_percent"]["mean"] / 100), 4),
                fmt(gs["runtime_ms"]["mean"], 3),
                fmt(gs["messages"]["mean"]),
            ]
        )
        rows.append(
            [
                f"Auction Jacobi ({r['case']})",
                n,
                m,
                fmt(cost * (1 + ja["gap_percent"]["mean"] / 100), 4),
                fmt(ja["runtime_ms"]["mean"], 3),
                fmt(ja["messages"]["mean"]),
            ]
        )
        rows.append(
            [
                f"Greedy ({r['case']})",
                n,
                m,
                fmt(cost * (1 + r["greedy"]["gap_percent"]["mean"] / 100), 4),
                "-",
                "-",
            ]
        )
        if r["case"] == "equal":
            for key, src in (("Hungarian", h), ("Auction (Gauss-Seidel)", gs), ("Auction (Jacobi)", ja)):
                runtime[key][0].append(n)
                runtime[key][1].append(max(src["runtime_ms"]["mean"], 1e-4))
        xs, ys = messages.setdefault(f"Jacobi, {r['case'].replace('_', ' ')}", ([], []))
        xs.append(n)
        ys.append(ja["messages"]["mean"])
    line_chart(
        runtime,
        "robots (= tasks)",
        "runtime [ms]",
        "Assignment runtime vs. team size",
        PLOTS / "allocation_runtime.png",
        logx=True,
        logy=True,
    )
    line_chart(
        messages,
        "robots",
        "messages",
        "Auction communication vs. team size",
        PLOTS / "allocation_messages.png",
        logx=True,
        logy=True,
    )
    dyn = [
        [
            r["switching_penalty"],
            fmt(r["mean_completion_time"]["mean"], 3),
            fmt(r["max_completion_time"]["mean"], 3),
            fmt(r["reassignments"]["mean"], 2),
        ]
        for r in result["dynamic"]
    ]
    multi = [
        [
            r["objective"],
            r["robots"],
            r["tasks"],
            fmt(r["total_length"]["mean"], 4),
            fmt(r["max_route_length"]["mean"], 4),
            fmt(r["runtime_ms"]["mean"], 3),
        ]
        for r in result["multi_task"]
    ]
    text = header(
        "Task-allocation benchmarks", "mrc_experiment_allocation_benchmark", EXPERIMENTS["allocation"]
    )
    text += (
        "Random Euclidean instances in a 50 m square, mean over seeds. Cost is the total robot-to-task "
        "distance [m]. The auction uses the default eps (total error at most 0.1% of the largest cost); "
        "messages follow the shared-price-board model (one message per bid, one broadcast per price "
        "change). Greedy repeatedly takes the globally cheapest remaining pair.\n\n"
    )
    text += markdown_table(["Algorithm", "Robots", "Tasks", "Cost", "Runtime [ms]", "Messages"], rows)
    text += "\n\n![runtime](../assets/plots/allocation_runtime.png)\n\n"
    text += "![messages](../assets/plots/allocation_messages.png)\n\n"
    text += (
        "The auction reaches the optimum within its eps bound in every case. Its cost is communication: "
        "when robots outnumber tasks they bid prices up through many small increments (price wars), so "
        "rounds and messages grow by orders of magnitude while the centralised Hungarian method stays "
        "below a few milliseconds. The distributed method is not expected to beat the centralised optimum; "
        "it trades runtime and messages for decentralised decision making.\n\n"
        "## Dynamic arrivals\n\nEight robots, Poisson task arrivals (0.6 tasks/s for 120 s); dynamic "
        "reallocation with a 1 m commitment radius and different switching penalties.\n\n"
    )
    text += markdown_table(
        ["Switching penalty", "Mean completion [s]", "Max completion [s]", "Reassignments"], dyn
    )
    text += (
        "\n\nA small penalty removes most reassignments (thrashing) without hurting completion times.\n\n"
        "## Multiple tasks per robot (SSI auctions)\n\n"
    )
    text += markdown_table(
        ["Objective", "Robots", "Tasks", "Total length [m]", "Longest route [m]", "Runtime [ms]"], multi
    )
    text += "\n\nMiniMax bids trade total travel for a shorter longest route (makespan proxy).\n"
    (DOCS / "allocation.md").write_text(text, encoding="utf-8")


def optimization_page(result: dict) -> None:
    rows = []
    series: dict[str, tuple[list, list]] = {}
    for r in result["rows"]:
        conv = f"{r['converged_runs']}/{r['runs']}"
        rows.append(
            [
                r["method"].upper(),
                r["topology"],
                r["robots"],
                fmt(r["iterations"]["mean"]),
                conv,
                fmt(r["final_solution_error"]["mean"], 3),
                fmt(r["messages"]["mean"]),
                fmt(r["runtime_ms"]["mean"], 3),
            ]
        )
        if r["topology"] == "random_geometric":
            xs, ys = series.setdefault(r["method"].upper(), ([], []))
            xs.append(r["robots"])
            ys.append(r["iterations"]["mean"])
    line_chart(
        series,
        "robots",
        "communication rounds (cap 20,000)",
        "Bearing localisation: rounds to 1e-4 relative error",
        PLOTS / "optimization_rounds.png",
        logx=True,
        logy=True,
    )
    text = header(
        "Distributed optimisation benchmarks",
        "mrc_experiment_optimization_benchmark",
        EXPERIMENTS["optimization"],
    )
    text += (
        "Cooperative bearing-only target localisation: each robot holds one noisy bearing (0.03 rad), "
        "i.e. a rank-one least-squares term, and starts from its own position. Stopping criterion: "
        "every robot within 1e-4 (1 + ||x*||) of the centralised least-squares solution, at most 20,000 "
        "rounds. One round = one exchange of estimates with all neighbours (2 |E| messages).\n\n"
    )
    text += markdown_table(
        [
            "Method",
            "Topology",
            "Robots",
            "Rounds",
            "Converged",
            "Final error [m]",
            "Messages",
            "Runtime [ms]",
        ],
        rows,
    )
    text += "\n\n![rounds](../assets/plots/optimization_rounds.png)\n\n"
    text += (
        "Decentralised ADMM reaches the optimum in tens to a few hundred rounds. Distributed gradient "
        "descent with a diminishing step converges sublinearly and does not reach the tolerance within "
        "the round budget; with a constant step it stalls in a neighbourhood of the optimum whose size "
        "shrinks with the step (verified in the unit tests).\n"
    )
    (DOCS / "optimization.md").write_text(text, encoding="utf-8")


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--run", action="store_true", help="run the experiment executables first")
    parser.add_argument("--build-dir", type=Path, default=None)
    args = parser.parse_args()
    DOCS.mkdir(parents=True, exist_ok=True)
    results = {}
    for name, config in EXPERIMENTS.items():
        path = RESULTS / f"{name}_benchmark.json"
        if args.run:
            pipeline.run_executable(f"mrc_experiment_{name}_benchmark", args.build_dir, ROOT / config, path)
        results[name] = pipeline.load_result(path)
    consensus_page(results["consensus"])
    formation_page(results["formation"])
    allocation_page(results["allocation"])
    optimization_page(results["optimization"])
    print("wrote docs/benchmarks/{consensus,formation,allocation,optimization}.md and plots")


if __name__ == "__main__":
    main()
