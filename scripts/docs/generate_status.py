"""Generates the algorithm status matrix from configs/algorithms.yaml.

Every column is derived from the repository (file existence), not asserted.
The matrix is written to docs/status.md and spliced into README.md between
the markers <!-- status:begin --> and <!-- status:end -->.

Usage: python scripts/docs/generate_status.py [--check]
  --check  exit non-zero if README.md or docs/status.md are out of date
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[2]
REGISTRY = ROOT / "configs" / "algorithms.yaml"
README = ROOT / "README.md"
STATUS = ROOT / "docs" / "status.md"
BEGIN = "<!-- status:begin -->"
END = "<!-- status:end -->"
YES = "✅"
NO = "—"


def exists(rel: str | None) -> bool:
    return bool(rel) and (ROOT / rel).exists()


def row(entry: dict) -> list[str]:
    implemented = exists(entry.get("header"))
    tests = entry.get("tests") or []
    tested = implemented and bool(tests) and all(exists(t) for t in tests)
    demo = exists(entry.get("demo")) and (entry.get("asset") is None or exists(entry.get("asset")))
    bench = exists(entry.get("benchmark"))
    name = entry["name"]
    if entry.get("docs") and exists(entry["docs"]):
        name = f"[{name}]({entry['docs']})"
    return [
        entry["area"],
        name,
        YES if implemented else "not implemented",
        YES if tested else NO,
        YES if demo else NO,
        YES if bench else NO,
    ]


def build_table() -> str:
    entries = yaml.safe_load(REGISTRY.read_text(encoding="utf-8"))["algorithms"]
    lines = ["| Area | Algorithm | Implemented | Tested | Demo | Benchmark |", "|---|---|---|---|---|---|"]
    lines += ["| " + " | ".join(row(e)) + " |" for e in entries]
    return "\n".join(lines)


def splice(text: str, table: str, link_prefix: str = "") -> str:
    if BEGIN not in text or END not in text:
        raise SystemExit(f"markers {BEGIN} / {END} not found")
    if link_prefix:
        table = table.replace("](docs/", f"]({link_prefix}")
    head, rest = text.split(BEGIN, 1)
    _, tail = rest.split(END, 1)
    return f"{head}{BEGIN}\n{table}\n{END}{tail}"


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    table = build_table()
    status_text = (
        "# Algorithm status\n\nGenerated by `scripts/docs/generate_status.py` from "
        "`configs/algorithms.yaml`; every column is checked against the repository.\n\n"
        f"{BEGIN}\n{table.replace('](docs/', '](')}\n{END}\n"
    )
    readme_text = splice(README.read_text(encoding="utf-8"), table)
    if args.check:
        stale = []
        if README.read_text(encoding="utf-8") != readme_text:
            stale.append("README.md")
        if not STATUS.exists() or STATUS.read_text(encoding="utf-8") != status_text:
            stale.append("docs/status.md")
        if stale:
            print("out of date:", ", ".join(stale))
            sys.exit(1)
        print("status matrix up to date")
        return
    README.write_text(readme_text, encoding="utf-8", newline="\n")
    STATUS.write_text(status_text, encoding="utf-8", newline="\n")
    print("updated README.md and docs/status.md")


if __name__ == "__main__":
    main()
